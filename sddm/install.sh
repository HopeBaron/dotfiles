#!/usr/bin/env bash
# Install the Caelestia login theme for SDDM and make it the active one.
#
#   ./sddm/install.sh      (asks for sudo)
#
# Re-run it after changing the colour scheme or wallpaper: the greeter runs as
# the sddm user, which cannot read your home folder, so the theme is a COPY with
# the current scheme colours and wallpaper baked in, not a link into the repo.
set -euo pipefail

readonly HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
readonly STATE=${XDG_STATE_HOME:-$HOME/.local/state}/caelestia
readonly DEST=/usr/share/sddm/themes/caelestia

[[ -f "$STATE/scheme.json" ]] || { echo "no scheme yet -- run: caelestia scheme set -n caelestia" >&2; exit 1; }

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT
cp "$HERE"/caelestia/{Main.qml,metadata.desktop} "$stage/"

# The wallpaper the shell is showing, if it can be found.
bg=""
wp=$(cat "$STATE/wallpaper/path.txt" 2>/dev/null || true)
if [[ -f "$wp" ]]; then
  bg="background.${wp##*.}"
  cp "$wp" "$stage/$bg"
fi

python3 - "$STATE/scheme.json" "$stage/theme.conf" "$bg" <<'PY'
import json, sys
scheme, out, bg = sys.argv[1:4]
c = json.load(open(scheme))["colours"]
keys = ["background", "onBackground", "surfaceContainer", "surfaceContainerHigh", "onSurface",
        "onSurfaceVariant", "outline", "outlineVariant", "primary", "onPrimary", "error", "tertiary"]
with open(out, "w") as f:
    f.write("# GENERATED by sddm/install.sh from the Caelestia scheme -- do not edit.\n[General]\n")
    f.write("font=Rubik\niconFont=Material Symbols Rounded\n")
    for k in keys:
        f.write(f"{k}=#{c[k]}\n")
    f.write(f"background_image={bg}\n")
PY

sudo rm -rf "$DEST"
sudo install -Dm644 -t "$DEST" "$stage"/*
printf '[Theme]\nCurrent=caelestia\n# Same cursor Hyprland ends up with (icons/default inherits Adwaita, size 24).\nCursorTheme=Adwaita\nCursorSize=24\n' \
  | sudo tee /etc/sddm.conf.d/10-caelestia.conf >/dev/null

# The old v2 theme and its config, if still there.
sudo rm -f /etc/sddm.conf.d/10-gruvbox-material.conf
sudo rm -rf /usr/share/sddm/themes/gruvbox-material

echo "Installed. Preview without logging out:  sddm-greeter-qt6 --test-mode --theme $DEST"
